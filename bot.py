CYCLES = {
    "fajr":  ["ayah", "hadith", "zikr", "dua", "prophet", "surah", "hadith"],
    "night": ["zikr", "ayah", "hadith", "dua", "surah", "prophet", "ayah"],
}
BUILDERS = {"ayah": build_ayah, "hadith": build_hadith, "zikr": build_zikr,
            "dua": build_dua, "prophet": build_prophet, "surah": build_surah}


def generate_post(day, slot):
    cycle = CYCLES[slot]
    cat = cycle[day % len(cycle)]
    slot_idx = 0 if slot == "fajr" else 1
    order = [cat] + [c for c in ("hadith", "dua") if c != cat]  # احتياطي لو فشل الـ API
    for c in order:
        k = nth(cycle, day, c)
        out = BUILDERS[c](day=day, slot_idx=slot_idx, k=k, slot=slot)
        if out:
            return out
    return None


def compose():
    now = datetime.now(TZ)
    slot = os.environ.get("SLOT") or ("fajr" if now.hour < 12 else "night")
    day = (now.date() - date(2025, 1, 1)).days

    body = generate_post(day, slot)
    if not body:
        return None
    hijri = get_hijri(now)
    greeting = "🌅 <b>وقت السَّحَر والفجر</b>" if slot == "fajr" else "🌙 <b>ختام اليوم</b>"
    date_line = f"🗓 {WEEKDAYS[now.weekday()]} {hijri['day']} {esc(hijri['month_ar'])} {hijri['year']}هـ" if hijri \
        else f"🗓 {WEEKDAYS[now.weekday()]} {now:%Y-%m-%d}"
    notes = "\n\n".join(occasion_notes(now, slot, hijri))
    parts = [f"{greeting}\n<i>{date_line}</i>", body]
    if notes:
        parts.append(notes)
    parts.append(f"──────────\n{SIGNATURE}")
    msg = "\n\n".join(parts)
    return msg if len(msg) <= TELEGRAM_LIMIT else "\n\n".join([parts[0], body, parts[-1]])[:TELEGRAM_LIMIT]


def load_channels():
    raw = os.environ.get("CHANNEL_ID", "")
    out = []
    for part in raw.replace("\n", ",").split(","):
        part = part.strip()
        if not part:
            continue
        if part.lstrip("-").isdigit():
            out.append(int(part))
        else:
            out.append(part if part.startswith("@") else "@" + part)
    return out or FALLBACK_CHANNELS


def send(chat_id, text):
    url = f"https://api.telegram.org/bot{BOT_TOKEN}/sendMessage"
    payload = {"chat_id": chat_id, "text": text, "parse_mode": "HTML", "disable_web_page_preview": True}
    for _ in range(3):
        try:
            r = session.post(url, json=payload, timeout=15)
            data = r.json()
        except Exception as e:
            print(f"⚠️ خطأ اتصال أثناء الإرسال إلى {chat_id}: {type(e).__name__}")
            time.sleep(2)
            continue
        if data.get("ok"):
            return True
        if r.status_code == 429:
            wait = data.get("parameters", {}).get("retry_after", 5)
            print(f"⏳ حد الإرسال، انتظار {wait}ث")
            time.sleep(wait + 1)
            continue
        print(f"❌ فشل النشر في {chat_id}: {data.get('description')}")
        return False
    return False


