esc = html.escape


def get_json(url, tries=3, timeout=12):
    for i in range(tries):
        try:
            r = session.get(url, timeout=timeout)
            r.raise_for_status()
            return r.json()
        except Exception as e:
            print(f"⚠️ فشل جلب {url} (محاولة {i + 1}): {type(e).__name__}")
            time.sleep(1.5 * (i + 1))
    return None


def trim(text, limit):
    text = " ".join(text.split())
    if len(text) <= limit:
        return text
    return text[:limit].rsplit(" ", 1)[0] + "…"


def clean_ayah(text, surah_no, num):
    # الـ API يضيف البسملة أول الآية الأولى من كل سورة عدا الفاتحة
    if num == 1 and surah_no != 1:
        words = text.split()
        if len(words) > 4 and words[0].startswith("بِسْمِ"):
            return " ".join(words[4:])
    return text


def fetch_one(ref):
    """ref: رقم الآية في المصحف أو 'سورة:آية' — يرجع النص العثماني + التفسير الميسر"""
    d = get_json(f"{QURAN_API}/ayah/{ref}/editions/quran-uthmani,ar.muyassar")
    try:
        a, t = d["data"]
        s, n = a["surah"]["number"], a["numberInSurah"]
        return {"text": clean_ayah(a["text"], s, n).strip(), "tafsir": t["text"].strip(), "s": s, "n": n}
    except Exception:
        return None


def fetch_passage(s, a, b):
    parts = []
    for n in range(a, b + 1):
        p = fetch_one(f"{s}:{n}")
        if not p:
            return None
        parts.append(p)
    return {
        "text": " ".join(p["text"] for p in parts),
        "tafsir": " ".join(p["tafsir"] for p in parts),
        "label": label(s, a, b),
    }


def label(s, a, b):
    name = SURAHS[s - 1]
    return f"سورة {name} — الآية {a}" if a == b else f"سورة {name} — الآيات {a}-{b}"


def quran_block(refs):
    blocks, labels = [], []
    for (s, a, b) in refs:
        p = fetch_passage(s, a, b)
        if not p:
            return None, None
        blocks.append(f"﴿ {esc(p['text'])} ﴾")
        labels.append(p["label"])
    return "\n\n".join(blocks), "؛ ".join(labels)


def nth(cycle, day, cat):
    """كم مرة ظهرت هذه الفئة قبل اليوم → فهرس العنصر (بلا تكرار حتى تنتهي القائمة)"""
    full, rem = divmod(day, len(cycle))
    return full * cycle.count(cat) + cycle[:rem].count(cat)


def pick(lst, k):
    return lst[k % len(lst)]


