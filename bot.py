def build_ayah(day, slot_idx, **_):
    rng = random.Random(day * 2 + slot_idx)
    for _ in range(8):
        p = fetch_one(str(rng.randint(1, 6236)))
        if p and len(p["text"]) <= 400:
            return (
                "📖 <b>آية وتدبّر</b>\n\n"
                f"<blockquote>﴿ {esc(p['text'])} ﴾</blockquote>\n"
                f"📌 {esc(label(p['s'], p['n'], p['n']))}\n\n"
                "📝 <b>التفسير الميسر:</b>\n"
                f"<blockquote>{esc(trim(p['tafsir'], 700))}</blockquote>"
            )
    return None


def build_hadith(k, slot, **_):
    pool = HADITHS + (HADITHS_FAJR if slot == "fajr" else HADITHS_NIGHT)
    h = pick(pool, k)
    return (
        "📜 <b>حديث نبوي شريف</b>\n\n"
        f"<blockquote>{esc(h['text'])}</blockquote>\n"
        f"🗣 <b>الراوي:</b> {esc(h['narrator'])}\n"
        f"📚 <b>المصدر:</b> {esc(h['source'])}\n"
        f"✅ <b>الدرجة:</b> {esc(h['grade'])}"
    )


def build_zikr(k, slot, **_):
    allowed = ("morning", "both") if slot == "fajr" else ("evening", "night", "both")
    z = pick([x for x in AZKAR if x["when"] in allowed], k)
    if "refs" in z:
        body, _lbl = quran_block(z["refs"])
        if body is None:
            return None
    else:
        body = f"<blockquote>{esc(z['text'])}</blockquote>"
    return (
        f"🌿 <b>{esc(z['type'])}</b>\n\n{body}\n\n"
        f"✨ <b>الفضل:</b> {esc(z['virtue'])}\n"
        f"📚 <b>المصدر:</b> {esc(z['source'])}"
    )


def build_dua(k, **_):
    d = pick(DUAS, k)
    if "refs" in d:
        body, lbl = quran_block(d["refs"])
        if body is None:
            return None
        src = d.get("source") or lbl
        body = body if not d.get("source") else f"{body}\n\n📌 {esc(lbl)}"
    else:
        body, src = f"<blockquote>{esc(d['text'])}</blockquote>", d["source"]
    return f"🤲 <b>{esc(d['title'])}</b>\n\n{body}\n\n📚 <b>المصدر:</b> {esc(src)}"


def build_surah(k, **_):
    v = pick(SURAH_VIRTUES, k)
    n = v["n"]
    meta = get_json(f"{QURAN_API}/surah/{n}")
    info = ""
    try:
        m = meta["data"]
        kind = "مكية" if m["revelationType"] == "Meccan" else "مدنية"
        info = f"\n🔢 ترتيبها في المصحف: {n} — {kind} — عدد آياتها: {m['numberOfAyahs']}"
    except Exception:
        info = f"\n🔢 ترتيبها في المصحف: {n}"
    return (
        f"📖 <b>سورة اليوم: {esc(SURAHS[n - 1])}</b>{info}\n\n"
        f"✨ <b>فضلها:</b>\n<blockquote>{esc(v['virtue'])}</blockquote>\n"
        f"📚 <b>المصدر:</b> {esc(v['source'])}"
    )


def build_prophet(k, **_):
    p = pick(PROPHETS, k)
    out = (
        "⭐ <b>من قصص الأنبياء والعِبر</b>\n\n"
        f"نبي الله <b>{esc(p['name'])}</b> — {esc(p['desc'])}\n\n"
        f"💡 <b>العبرة:</b> {esc(p['lesson'])}\n"
        f"📖 <b>موضع قصته:</b> {esc(p['where'])}"
    )
    s, a, b = p["key"]
    ps = fetch_passage(s, a, b)
    if ps:
        out += f"\n\n<blockquote>﴿ {esc(ps['text'])} ﴾</blockquote>\n📌 {esc(ps['label'])}"
    return out


