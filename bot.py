def get_random_ayah():
    try:
        ayah_num = random.randint(1, 6236)
        res = requests.get(f"https://api.alquran.cloud/v1/ayah/{ayah_num}/quran-uthmani", timeout=10).json()
        data = res["data"]
        return f"📖 <b>آية كريمة:</b>\n\n﴿ {data['text']} ﴾\n\n📌 سورة {data['surah']['name']} — الآية رقم ({data['numberInSurah']})"
    except Exception:
        h = random.choice(HADITHS)
        return f"📜 <b>حديث نبوي شريف:</b>\n\n{h['text']}\n\n📚 المصدر: {h['source']}"

def generate_post():
    category = random.choice(["ayah", "surah", "hadith", "prophet", "zikr", "dua"])
    
    if category == "ayah":
        return get_random_ayah()
    elif category == "surah":
        s_name = random.choice(SURAHS)
        idx = SURAHS.index(s_name) + 1
        return f"📖 <b>سورة اليوم للتدبر:</b>\n\nسورة <b>{s_name}</b> (ترتيبها في المصحف: {idx})\n\n💡 قال رسول الله ﷺ: «من قرأ حرفاً من كتاب الله فله به حسنة، والحسنة بعشر أمثالها»."
    elif category == "hadith":
        h = random.choice(HADITHS)
        return f"📜 <b>حديث نبوي شريف:</b>\n\n{h['text']}\n\n📚 المصدر: {h['source']}"
    elif category == "prophet":
        p = random.choice(PROPHETS)
        return f"⭐ <b>من قصص الأنبياء والعِبر:</b>\n\nنبي الله: <b>{p['name']}</b> ({p['desc']})\n\n💡 <b>الدرس والعِبرة:</b>\n{p['lesson']}"
    elif category == "zikr":
        z = random.choice(AZKAR)
        return f"🌿 <b>{z['type']}:</b>\n\n{z['text']}\n\n✨ <b>الفضل والأثر:</b>\n{z['virtue']}"
    elif category == "dua":
        d = random.choice(DUAS)
        return f"🤲 <b>{d['title']}:</b>\n\n{d['text']}\n\n📌 <b>المصدر:</b> {d['source']}"

def broadcast():
    if not BOT_TOKEN:
        print("خطأ: لم يتم العثور على BOT_TOKEN في المتغيرات البيئية.")
        return

    if not CHANNELS:
        print("خطأ: مصفوفة CHANNELS فارغة. يرجى إضافة القنوات أولاً.")
        return

    content = generate_post()
    # رابط المنصة مع نص غير مائل
    signature = '🕌 <a href="https://alfathplatform.vercel.app">منصة الفتح</a>'
    message = f"{content}\n\n---\n{signature}"
    
    url = f"https://api.telegram.org/bot{BOT_TOKEN}/sendMessage"
    success_count = 0

    for chat_target in CHANNELS:
        payload = {
            "chat_id": chat_target,
            "text": message,
            "parse_mode": "HTML",
            "disable_web_page_preview": True
        }
        try:
            res = requests.post(url, json=payload, timeout=12).json()
            if res.get("ok"):
                print(f"✅ تم النشر في: {chat_target}")
                success_count += 1
            else:
                print(f"❌ فشل النشر في {chat_target}: {res.get('description')}")
        except Exception as e:
            print(f"⚠️ استثناء أثناء الإرسال إلى {chat_target}: {e}")
        
        time.sleep(0.2)

    print(f"\nاكتملت العملية: نُشر بنجاح في {success_count} من {len(CHANNELS)} قناة/مجموعة.")

if __name__ == "__main__":
    broadcast()
