def get_random_ayah():
    try:
        ayah_num = random.randint(1, 6236)
        res = requests.get(f"https://api.alquran.cloud/v1/ayah/{ayah_num}/ar.asad", timeout=10).json()
        data = res["data"]
        return f"📖 <b>آية كريمة:</b>\n\n﴿ {data['text']} ﴾\n\n📌 سورة {data['surah']['name']} — الآية رقم ({data['numberInSurah']})"
    except Exception:
        h = random.choice(HADITHS)
        return f"📜 <b>حديث نبوي شريف:</b>\n\n{h['text']}\n\n📚 المصدر: {h['source']}"

def generate_post():
    category = random.choice(["ayah", "surah", "hadith", "prophet"])
    
    if category == "ayah":
        return get_random_ayah()
    elif category == "surah":
        s_name = random.choice(SURAHS)
        idx = SURAHS.index(s_name) + 1
        return f"📖 <b>سورة اليوم للتدبر:</b>\n\nسورة <b>{s_name}</b> (ترتيبها في المصحف: {idx})\n\n💡 قال رسول الله ﷺ: «من قرأ حرفاً من كتاب الله فله به حسنة، والحسنة بعشر أمثالها»."
    elif category == "hadith":
        h = random.choice(HADITHS)
        return f"📜 <b>حديث نبوي شريف:</b>\n\n{h['text']}\n\n📚 المصدر: {h['source']}"
    elif category == "prophet":
        p = random.choice(PROPHETS)
        return f"⭐ <b>من قصص الأنبياء والعِبر:</b>\n\nنبي الله: <b>{p['name']}</b> ({p['desc']})\n\n💡 <b>الدرس والعِبرة:</b>\n{p['lesson']}"

def send_telegram():
    if not BOT_TOKEN or not CHANNEL_ID:
        print("خطأ: يرجى التأكد من إضافة BOT_TOKEN و CHANNEL_ID في Secrets")
        return

    content = generate_post()
    message = f"{content}\n\n---\n🕌 <i>منصة الفتح</i>"
    
    url = f"https://api.telegram.org/bot{BOT_TOKEN}/sendMessage"
    payload = {
        "chat_id": CHANNEL_ID,
        "text": message,
        "parse_mode": "HTML"
    }
    
    response = requests.post(url, json=payload, timeout=15)
    print("Response:", response.json())

if __name__ == "__main__":
    send_telegram()
